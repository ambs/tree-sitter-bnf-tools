/// A wrapper that renders a [`Grammar`]'s derived visitor shape (see the
/// parent [`super`] module) as a complete Rust source file containing an
/// ANTLR-style `Visitor<'tree>` trait — one `visit_<kind>` method per
/// visible node kind, plus a `visit()` dispatcher and a `combine`-based fold.
///
/// Mirrors [`super::super::Scaffold`]'s shape: a reference to the grammar
/// plus the same header-comment fields, so the two emitters read the same
/// way even though one renders `grammar.js` and the other a Rust trait.
///
/// Only buildable via [`RustVisitor::new`], not as a struct literal: that
/// constructor runs [`check_visitor`] before a `RustVisitor` can exist at
/// all, so a grammar whose kinds would collide into the same `visit_*`
/// method name is rejected there — with a clear diagnostic naming both
/// offending kinds — rather than silently rendered into Rust source with
/// two same-named method definitions that only fails later, at `rustc` time,
/// in whatever downstream build happens to compile the generated file.
pub struct RustVisitor<'a> {
    /// The grammar to derive the trait from.
    grammar: &'a Grammar,
    /// The grammar's name, used in the generated trait's doc comment (e.g.
    /// "ANTLR-style visitor for the `decls` tree-sitter grammar.").
    name: &'a str,
    /// The source filename shown in the generated-file header (`<stdin>` for stdin).
    source: &'a str,
    /// When `true`, suppress the generated-file header comment.
    no_header: bool,
}

impl<'a> RustVisitor<'a> {
    /// Builds a `RustVisitor` for `grammar`, or an `Err` naming the
    /// colliding kinds if [`check_visitor`] rejects it.
    ///
    /// This is the only way to construct a `RustVisitor` — see the type's
    /// own doc comment for why the check can't be skipped by construction.
    ///
    /// - `name`: the grammar's name, used in the generated trait's doc
    ///   comment.
    /// - `source`: the source filename shown in the generated-file header
    ///   (`<stdin>` for stdin).
    /// - `no_header`: when `true`, suppresses the generated-file header
    ///   comment.
    pub fn new(
        grammar: &'a Grammar,
        name: &'a str,
        source: &'a str,
        no_header: bool,
    ) -> Result<Self, String> {
        check_visitor(grammar)?;
        Ok(Self {
            grammar,
            name,
            source,
            no_header,
        })
    }
}

impl RustVisitor<'_> {
    /// Emits the generated-file header comment, unless suppressed by
    /// `no_header` — identical wording to [`super::super::Scaffold`]'s, since
    /// this is also generated code that shouldn't be hand-edited. Unlike
    /// `Scaffold::fmt_header`, a blank line follows the comment: the next
    /// thing emitted is a Rust `use` statement, and comment-blank-`use` reads
    /// more naturally than comment-immediately-`use`.
    fn fmt_header(&self, f: &mut Formatter<'_>) -> fmt::Result {
        if !self.no_header {
            let version = env!("CARGO_PKG_VERSION");
            writeln!(
                f,
                "// Generated by ts-bnf-tool v{version} from {} \u{2014} do not edit by hand.",
                self.source
            )?;
            writeln!(f)?;
        }
        Ok(())
    }

    /// Emits the `use` import, the `Visitor<'tree>` trait's own doc comment
    /// (ANTLR correspondence table, `combine`-pattern table, minimal
    /// example), and the trait's opening line.
    ///
    /// This is the doc a reader sees when they open the generated file and
    /// look at `Visitor`'s definition — since they won't have read the
    /// design rationale behind it, it has to stand alone: what ANTLR concept
    /// each method corresponds to, what `combine` is supposed to do for a
    /// few common `Output` shapes, and one small worked-through
    /// implementation. One `formatdoc!` block, rather than a `writeln!` per
    /// line, since this is fixed text with a single interpolated value (the
    /// grammar `name`) — same choice `main.rs` makes for its own
    /// multi-line generated-file content.
    fn fmt_trait_doc(&self, f: &mut Formatter<'_>) -> fmt::Result {
        let name = self.name;
        let antlr_table = prefix_lines(
            &render_table(&[
                ["ANTLR (`AbstractParseTreeVisitor`)", "Here"],
                ["`visit(tree)`", "[`Visitor::visit`]"],
                ["`visitChildren(node)`", "[`Visitor::children_visitor`]"],
                [
                    "`aggregateResult(agg, next)`",
                    "[`Visitor::combine`] (`Vec`-based, not pairwise)",
                ],
                [
                    "`defaultResult()`",
                    "[`Visitor::default_result`] (`= combine(vec![])`)",
                ],
                ["`visitErrorNode(node)`", "[`Visitor::error_visitor`]"],
                [
                    "(no ANTLR analogue)",
                    "[`Visitor::missing_visitor`], for tree-sitter's `MISSING` nodes",
                ],
            ]),
            "///",
        );
        let combine_table = prefix_lines(
            &render_table(&[
                ["Output type", "Typical `combine` body"],
                ["`()` (side-effect)", "`Ok(())`"],
                [
                    "`Vec<T>` (collect)",
                    "`Ok(results.into_iter().flatten().collect())`",
                ],
                [
                    "`Option<T>` (find-first)",
                    "`Ok(results.into_iter().flatten().next())`",
                ],
            ]),
            "///",
        );
        write!(
            f,
            "{}",
            formatdoc! {r#"
                use tree_sitter::Node;

                /// ANTLR-style visitor for the `{name}` tree-sitter grammar.
                ///
                /// ## How to implement
                ///
                /// Implement [`Visitor::combine`], folding a `Vec` of child outputs into
                /// one output, and override whichever `visit_<kind>` methods you care
                /// about. Every method you don't override falls back to a sensible
                /// default: non-leaf kinds recurse via [`Visitor::children_visitor`], leaf
                /// kinds return [`Visitor::default_result`].
                ///
                /// ## ANTLR correspondence
                ///
                {antlr_table}
                ///
                /// ## `combine` patterns
                ///
                {combine_table}
                ///
                /// ## Minimal example
                ///
                /// ```ignore
                /// struct Counter(usize);
                ///
                /// impl<'t> Visitor<'t> for Counter {{
                ///     type Output = ();
                ///     type Error = std::convert::Infallible;
                ///
                ///     fn combine(&mut self, _: Vec<()>) -> Result<(), Self::Error> {{
                ///         Ok(())
                ///     }}
                ///
                ///     fn visit_decl(&mut self, node: Node<'t>) -> Result<(), Self::Error> {{
                ///         self.0 += 1;
                ///         self.children_visitor(node)
                ///     }}
                /// }}
                /// ```
                pub trait Visitor<'tree> {{
            "#}
        )
    }

    /// Emits the trait's two associated types, the required `combine`
    /// method, and the five ANTLR-mirroring helpers with their default
    /// bodies (`children_visitor`, `field_visitor`, `default_result`,
    /// `error_visitor`, `missing_visitor` — see [`RustVisitor::fmt_trait_doc`]'s
    /// ANTLR correspondence table for what each one maps to).
    ///
    /// Every kind-derived `visit_<kind>` method is exactly `visit_<kind>`,
    /// and none of these five helpers start with `visit_` (they use a
    /// `_visitor` suffix instead) — so a kind name can never collide with
    /// one of them; [`super::check_method_name_collisions`] only has to
    /// guard against kind/kind collisions, not kind/helper ones.
    ///
    /// Each member is written flush-left here (readable to write and
    /// review), `trim_end`-ed to drop indoc's own trailing newline, joined
    /// with a blank line between members, and indented one level in a
    /// single pass via [`indent`] — hand-typing the leading spaces into
    /// every source line is exactly what produced the markdown-table test
    /// failure earlier, so a single programmatic indent pass replaces that
    /// everywhere in this file.
    fn fmt_core_members(&self, f: &mut Formatter<'_>) -> fmt::Result {
        let members = [
            indoc! {r#"
                /// The value produced by each `visit_*` call.
                type Output;

                /// The error type. Use `std::convert::Infallible` for a
                /// visitor that can't fail.
                type Error;
            "#},
            indoc! {r#"
                /// Merges child outputs into a single output.
                ///
                /// This is the only method you *must* implement. Called by
                /// [`Visitor::children_visitor`] and [`Visitor::field_visitor`]
                /// with one [`Visitor::Output`] per visited child, and by
                /// [`Visitor::default_result`] with an empty `Vec`.
                fn combine(&mut self, results: Vec<Self::Output>) -> Result<Self::Output, Self::Error>;
            "#},
            indoc! {r#"
                /// Walks all named children of `node` and combines their outputs.
                ///
                /// This is the default body of every non-leaf `visit_*`
                /// method. Anonymous children (punctuation, keywords) are
                /// silently skipped.
                fn children_visitor(&mut self, node: Node<'tree>) -> Result<Self::Output, Self::Error> {
                    let mut cursor = node.walk();
                    let mut results = Vec::new();
                    for child in node.named_children(&mut cursor) {
                        results.push(self.visit(child)?);
                    }
                    self.combine(results)
                }
            "#},
            indoc! {r#"
                /// Visits every child in field `field_name` and combines
                /// their outputs.
                ///
                /// Handles `multiple: true` fields correctly, visiting
                /// every match rather than just the first. Returns
                /// [`Visitor::default_result`] when the field is absent.
                fn field_visitor(
                    &mut self,
                    node: Node<'tree>,
                    field_name: &str,
                ) -> Result<Self::Output, Self::Error> {
                    let mut cursor = node.walk();
                    let mut results = Vec::new();
                    for child in node.children_by_field_name(field_name, &mut cursor) {
                        results.push(self.visit(child)?);
                    }
                    self.combine(results)
                }
            "#},
            indoc! {r#"
                /// The neutral output, `combine(vec![])`.
                ///
                /// ANTLR's `defaultResult()`. Return this from a leaf's
                /// `visit_*` method, or from any override meaning: handled,
                /// do not recurse.
                fn default_result(&mut self) -> Result<Self::Output, Self::Error> {
                    self.combine(vec![])
                }
            "#},
            indoc! {r#"
                /// Visits an `ERROR` node, one of tree-sitter's
                /// parse-recovery nodes.
                ///
                /// ANTLR's `visitErrorNode`. Defaults to recursing into its
                /// children.
                fn error_visitor(&mut self, node: Node<'tree>) -> Result<Self::Output, Self::Error> {
                    self.children_visitor(node)
                }
            "#},
            indoc! {r#"
                /// Visits a `MISSING` node, tree-sitter's zero-width
                /// parse-recovery marker.
                ///
                /// [`Node::kind`] reports the *expected* kind on a `MISSING`
                /// node, not a distinct missing kind, so [`Visitor::visit`]
                /// checks [`Node::is_missing`] before kind dispatch and
                /// routes here instead. Defaults to
                /// [`Visitor::default_result`]: treated as absent, not
                /// recursed into.
                fn missing_visitor(&mut self, node: Node<'tree>) -> Result<Self::Output, Self::Error> {
                    let _ = node;
                    self.default_result()
                }
            "#},
        ];
        let body = members
            .iter()
            .map(|m| m.trim_end())
            .collect::<Vec<_>>()
            .join("\n\n");
        writeln!(f, "{}", indent(&body, 4))
    }

    /// Emits the `visit()` dispatcher.
    ///
    /// [`Node::is_missing`] is checked before kind dispatch: `node.kind()`
    /// alone can't distinguish a `MISSING` node from an ordinary one of
    /// whatever kind the parser expected there, so a `MISSING` node always
    /// routes to `missing_visitor` regardless of what kind it reports.
    /// `"ERROR"` routes to `error_visitor`; every other kind not explicitly
    /// listed (anonymous tokens, kinds this grammar doesn't produce) falls
    /// through to `children_visitor`.
    ///
    /// One match arm per visible kind derived from the grammar (per
    /// [`visible_kinds`]), in the same order, each calling that kind's
    /// `visit_<kind>` method (per [`to_snake_case`]) — those per-kind
    /// methods are emitted by [`RustVisitor::fmt_visit_methods`].
    fn fmt_dispatcher(&self, f: &mut Formatter<'_>) -> fmt::Result {
        let arms = visible_kinds(self.grammar)
            .iter()
            .map(|kind| {
                let method = to_snake_case(kind);
                format!("        \"{kind}\" => self.visit_{method}(node),")
            })
            .collect::<Vec<_>>()
            .join("\n");
        let body = formatdoc! {r#"
            /// Dispatches `node` to the appropriate `visit_<kind>` method
            /// based on its kind.
            ///
            /// [`Node::is_missing`] is checked first: `node.kind()` alone
            /// can't distinguish a `MISSING` node from an ordinary one of
            /// whatever kind the parser expected there, so a `MISSING`
            /// node always routes to [`Visitor::missing_visitor`]
            /// regardless of what kind it reports.
            fn visit(&mut self, node: Node<'tree>) -> Result<Self::Output, Self::Error> {{
                if node.is_missing() {{
                    return self.missing_visitor(node);
                }}
                match node.kind() {{
            {arms}
                    "ERROR" => self.error_visitor(node),
                    _ => self.children_visitor(node),
                }}
            }}
        "#};
        writeln!(f, "\n{}", indent(body.trim_end(), 4))
    }

    /// Emits one documented `visit_<kind>` method per visible kind, each
    /// built by [`RustVisitor::fmt_visit_method`] and joined with a blank
    /// line between methods.
    fn fmt_visit_methods(&self, f: &mut Formatter<'_>) -> fmt::Result {
        let methods = visible_kinds(self.grammar)
            .iter()
            .map(|kind| self.fmt_visit_method(kind))
            .collect::<Vec<_>>()
            .join("\n\n");
        if methods.is_empty() {
            return Ok(());
        }
        writeln!(f, "\n{}", indent(&methods, 4))
    }

    /// Builds one `visit_<kind>` method's flush-left text: a doc comment
    /// listing `kind`'s resolved fields ([`collect_fields`]) and any
    /// anonymous children ([`collect_anonymous_children`]), followed by the
    /// method signature and a default body — [`Visitor::default_result`]
    /// for a leaf kind ([`is_leaf_body`]), [`Visitor::children_visitor`]
    /// otherwise.
    ///
    /// `body_for_kind(self.grammar, kind)` is expected to resolve for every
    /// `kind` this is called with: every caller sources `kind` from
    /// [`visible_kinds`], and [`body_for_kind`] is guaranteed to resolve
    /// every kind that function produces (see its own doc).
    fn fmt_visit_method(&self, kind: &str) -> String {
        let body =
            body_for_kind(self.grammar, kind).expect("every visible kind has a resolvable body");
        let method_name = to_snake_case(kind);
        let leaf = is_leaf_body(self.grammar, body);
        let fields = collect_fields(self.grammar, body);
        let anonymous = collect_anonymous_children(self.grammar, body);

        let mut doc = format!("Visits a `{kind}` node.\n");
        if !fields.is_empty() {
            doc.push_str("\n**Fields:**\n");
            for (field_name, target) in &fields {
                let mut options: Vec<String> = target
                    .named
                    .iter()
                    .map(|k| format!("`{k}` ([`Visitor::visit_{}`])", to_snake_case(k)))
                    .collect();
                if target.anonymous_token {
                    options.push("an anonymous token".to_string());
                }
                doc.push_str(&format!(
                    "- `{field_name}` -> {}, via `self.field_visitor(node, \"{field_name}\")`\n",
                    options.join(" | ")
                ));
            }
        }
        if !anonymous.is_empty() {
            let tokens = anonymous
                .iter()
                .map(|t| format!("`{t}`"))
                .collect::<Vec<_>>()
                .join(", ");
            doc.push_str(&format!(
                "\n**Anonymous children** (not visited by default): {tokens}\n"
            ));
        }
        if leaf {
            doc.push_str(
                "\n**Leaf node**: no visible children; defaults to [`Visitor::default_result`].\n",
            );
        }

        let doc_comment = prefix_lines(doc.trim_end(), "///");
        // A leaf's default body never touches `node` — same situation
        // `missing_visitor` has, fixed the same way:
        // `let _ = node;` suppresses the unused-variable warning without
        // renaming the parameter to `_node`, so it reads the same as every
        // other method here and an override can still just use `node`.
        let default_body = if leaf {
            "let _ = node;\n    self.default_result()"
        } else {
            "self.children_visitor(node)"
        };
        format!(
            "{doc_comment}\nfn visit_{method_name}(&mut self, node: Node<'tree>) -> Result<Self::Output, Self::Error> {{\n    {default_body}\n}}"
        )
    }
}

impl Display for RustVisitor<'_> {
    fn fmt(&self, f: &mut Formatter<'_>) -> fmt::Result {
        self.fmt_header(f)?;
        self.fmt_trait_doc(f)?;
        self.fmt_core_members(f)?;
        self.fmt_dispatcher(f)?;
        self.fmt_visit_methods(f)?;
        writeln!(f, "}}")
    }
}

