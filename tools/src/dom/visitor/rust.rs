    #[test]
    fn visit_method_non_leaf_kind_defaults_to_children_visitor() {
        // `num` (a leaf) comes right after `expr` (not a leaf), separated
        // by a blank line — bound the slice there. `num`'s *doc comment*
        // precedes its `fn visit_num(` line, so bounding at that line
        // instead would still leak "Leaf node" into the preceding slice.
        let g = Grammar::from_rules([
            p("expr", nt("num")),
            p("num", TerminalLiteral("'0'".into())),
        ]);
        let out = rv(&g, "g").to_string();
        let expr_method = out
            .split("fn visit_expr(")
            .nth(1)
            .and_then(|s| s.split("\n\n").next())
            .expect("visit_expr method present, followed by a blank line");
        assert!(expr_method.contains("self.children_visitor(node)"));
        assert!(!expr_method.contains("Leaf node"));
    }

