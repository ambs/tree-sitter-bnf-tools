    #[test]
    fn dispatcher_arms_are_indented_two_levels() {
        // Match arms sit inside `match node.kind() { ... }`, itself inside
        // `fn visit(...) { ... }`, itself inside the trait body — three
        // nesting levels, so 8 spaces, not the 4 that'd be enough for a
        // top-level trait member. `core_members_are_indented_one_level`
        // only checks "at least 4 spaces" across the whole body, which
        // would trivially pass even at the wrong (4-space) depth, so this
        // checks the arm lines specifically.
        let g = Grammar::from_rules([p("program", TerminalLiteral("'x'".into()))]);
        let out = rv(&g, "g").to_string();
        assert!(out.contains("        \"program\" => self.visit_program(node),"));
        assert!(!out.contains("\n    \"program\" => self.visit_program(node),"));
    }

